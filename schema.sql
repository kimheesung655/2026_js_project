-- 급식어때 Supabase 데이터베이스 구조
-- 새 Supabase 프로젝트의 SQL Editor에서 전체를 실행합니다.

create table if not exists public.schools (
  id bigint generated by default as identity primary key,
  school_name text not null,
  school_code text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  student_number text,
  school_id bigint references public.schools(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  menu_name text not null,
  rating numeric not null check (rating >= 1 and rating <= 5),
  content text not null,
  meal_date date not null,
  meal_type text not null default '중식' check (meal_type = '중식'),
  created_at timestamptz not null default now()
);

create index if not exists reviews_user_id_idx on public.reviews(user_id);
create index if not exists reviews_menu_name_idx on public.reviews(menu_name);
create index if not exists reviews_meal_date_idx on public.reviews(meal_date);


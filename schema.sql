drop policy if exists "학교 목록 조회" on public.schools;
create policy "학교 목록 조회"
on public.schools for select
using (true);

drop policy if exists "프로필 조회" on public.profiles;
create policy "프로필 조회"
on public.profiles for select
using (true);

drop policy if exists "본인 프로필 생성" on public.profiles;
create policy "본인 프로필 생성"
on public.profiles for insert
to authenticated
with check (auth.uid() = id);

drop policy if exists "본인 프로필 수정" on public.profiles;
create policy "본인 프로필 수정"
on public.profiles for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

